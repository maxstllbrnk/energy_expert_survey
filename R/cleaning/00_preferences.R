# 00_preferences.R — time and risk preference scores from the staircases
# Inputs : none; sourced by R/run_cleaning.R
# Outputs: none
# Checks : the first level of each staircase column is option A
################################################################################
# Q "Zeitpraeferenzen" and "Risikopraeferenzen" are the quantitative component of
# the Global Preference Survey (Falk, Becker, Dohmen, Enke, Huffman and Sunde,
# 2018, QJE, Section II.B). Each is up to five binary choices, and each choice sets
# the terms of the next one, so that the sequence closes in on the point where the
# expert is indifferent:
#
#   TIME  100 EUR today vs X EUR in 12 months. Taking the money today raises X for
#         the next question, waiting lowers it. X starts at 154 and ends between
#         103 and 215. Waiting is the patient answer, always option B.
#   RISK  a 50/50 lottery on 300 EUR vs a sure S EUR. Taking the lottery raises S,
#         the sure payment lowers it. S starts at 160 and ends between 10 and 310.
#         The lottery is the risk-tolerant answer, always option A.
#
# Five choices sort an expert into one of 32 ordered cells. The published GPS
# measure combines this staircase with a Likert self-assessment; this questionnaire
# has no such item, so this is the staircase component alone: a valid ordering of
# experts, not comparable to published GPS means.
#
# The five answers are read as a binary number, earliest choice most significant,
# with the patient or risk-tolerant answer counting as 1. <s>_score is the midpoint
# of the cell as a fraction of (0, 1). Two questions were never generated by
# LimeSurvey: an expert whose first three time answers were A, B, B stops after
# four. Others broke off. A shorter path gives a wider cell whose midpoint is the
# average of the narrower cells it contains. <s>_levels records the depth, so that
# shallow paths can be dropped. A z-score depends on the sample, so it is computed
# in the estimation script if a model uses one.

# The direction that counts as 1, and how to recognise option A: the columns are
# two-level factors whose first level must be option A, and nothing in the data says
# "A" any more, so its label is checked. If an export ever reversed the order, both
# scores would invert with nothing looking wrong.
STAIRCASES <- list(
  tp = list(prefix = "tp_", high = "B", option_a = "heute"),
  risk = list(prefix = "risk_", high = "A", option_a = "^Verlosung")
)

#' The columns of one staircase. tp_5bbba is level 5, reached after answering BBBA:
#' the letters after the digit are the answers given so far.
staircase_nodes <- function(data, prefix) {
  columns <- str_subset(names(data), paste0("^", prefix, "[0-9]"))
  stems <- str_remove(columns, paste0("^", prefix))
  tibble(column = columns,
         level = as.integer(str_sub(stems, 1, 1)),
         path = str_to_upper(str_sub(stems, 2)))
}

#' Follow each expert down the branch their own answers put them on. An expert who
#' skipped a level stops there: without the intermediate answer the path is unknown.
#'
#' @param data one row per expert, with the staircase columns
#' @param s    an element of STAIRCASES
#' @return tibble, one row per expert: cell, depth, max_depth (the deepest level the
#'   branch could reach), stray (answers on a branch never entered, left by going
#'   back in the questionnaire), score
walk_staircase <- function(data, s) {
  nodes <- staircase_nodes(data, s$prefix)
  for (column in nodes$column) {
    first_level <- levels(data[[column]])[1]
    if (length(levels(data[[column]])) != 2 || !str_detect(first_level, s$option_a)) {
      stop("The first level of ", column, " is \"", first_level, "\", which does not ",
           "look like option A: the score depends on option A coming first")
    }
  }
  n <- nrow(data)
  path <- rep("", n)
  cell <- rep(0L, n)
  depth <- rep(0L, n)
  is_active <- rep(TRUE, n)

  for (k in sort(unique(nodes$level))) {
    for (current_path in unique(path[is_active])) {
      column <- nodes$column[nodes$level == k & nodes$path == current_path]
      # this branch has no question at this level
      if (length(column) == 0) next
      rows <- is_active & path == current_path
      values <- data[[column]][rows]
      is_answered <- !is.na(values)
      if (!any(is_answered)) next
      positions <- which(rows)[is_answered]
      letters_answered <- if_else(as.integer(values[is_answered]) == 1L, "A", "B")
      path[positions] <- paste0(path[positions], letters_answered)
      cell[positions] <- cell[positions] * 2L + as.integer(letters_answered == s$high)
      depth[positions] <- k
    }
    is_active <- depth == k
  }

  stray <- integer(n)
  for (i in seq_len(nrow(nodes))) {
    is_on_path <- depth >= nodes$level[i] &
      str_sub(path, 1, str_length(nodes$path[i])) == nodes$path[i]
    stray <- stray + as.integer(!is.na(data[[nodes$column[i]]]) & !is_on_path)
  }

  # The deepest level each expert's branch could have reached, so that a path cut
  # short by the questionnaire differs from one cut short by the expert
  max_depth <- integer(n)
  for (current_path in unique(path)) {
    deepest <- 0L
    for (k in sort(unique(nodes$level))) {
      if (any(nodes$level == k & nodes$path == str_sub(current_path, 1, k - 1))) {
        deepest <- k
      }
    }
    max_depth[path == current_path] <- deepest
  }

  tibble(cell = cell, depth = depth, max_depth = max_depth, stray = stray,
         score = if_else(depth == 0L, NA_real_, (cell + 0.5) / 2^depth))
}

#' Adds, for each staircase <s> (tp, risk): <s>_score, <s>_cell, <s>_levels and
#' <s>_complete (the expert went as deep as their branch allows)
#'
#' @param data one row per expert, with the staircase columns
#' @return list: data, and report (one row per staircase: scored, broke_off,
#'   with_stray_answers, for the cleaning report)
add_preference_scores <- function(data) {
  report <- tibble()
  for (name in names(STAIRCASES)) {
    walked <- walk_staircase(data, STAIRCASES[[name]])
    data[[paste0(name, "_score")]] <- walked$score
    data[[paste0(name, "_cell")]] <- if_else(walked$depth == 0L, NA_integer_, walked$cell)
    data[[paste0(name, "_levels")]] <- walked$depth
    data[[paste0(name, "_complete")]] <- walked$depth > 0L & walked$depth == walked$max_depth
    report <- bind_rows(report, tibble(
      staircase = name,
      scored = sum(!is.na(walked$score)),
      broke_off = sum(walked$depth > 0 & walked$depth < walked$max_depth),
      with_stray_answers = sum(walked$stray > 0)
    ))
  }
  list(data = data, report = report)
}
